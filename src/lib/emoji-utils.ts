/**
 * Replaces Douyin-style emoji codes (e.g., [比心]) with Unicode emojis.
 */
export function replaceDouyinEmotes(text: string): string {
  if (!text) return text;
  return text.replace(/\[([\u4e00-\u9fa5a-zA-Z0-9]+)\]/g, (match) => {
    return EMOJI_MAP[match] || match;
  });
}
